/**
 * Pick the right dosha-details table based on language.
 * Falls back to undefined when language is not Hindi/Marathi so the caller
 * can use the canonical English DOSHA_DETAILS.
 */
export function pickDoshaDetails(lang) {
  const l = (lang ?? "en").toLowerCase().slice(0, 2);
  if (l === "hi" || l === "mr") return DOSHA_DETAILS_HI;
  return undefined;
}
